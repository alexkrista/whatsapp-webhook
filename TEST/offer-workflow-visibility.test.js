assert.doesNotMatch(workflow,/closed=\['offer_draft'/);
assert.doesNotMatch(tower,/\['offer_draft','order_approved'/);
console.log("OK: Angebotsmappen verschwinden beim Bearbeitungsstart nicht mehr.");
