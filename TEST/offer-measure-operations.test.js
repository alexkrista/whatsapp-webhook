const fs=require('fs'),assert=require('assert'),vm=require('vm');
const src=fs.readFileSync('public/ui/baustellen-offer-builder.js','utf8'),server=fs.readFileSync('server.js','utf8');
const a=src.indexOf('function measureLineUnit('),b=src.indexOf('\n',src.indexOf('function oneRoomAreas(',a));
const core=src.slice(a,b);
const sandbox={localNumber:v=>Number(String(v??0).replace(',','.'))||0};
vm.createContext(sandbox);vm.runInContext(core,sandbox);
const {measureLineValue:calc,measureLineOperation:op,oneRoomAreas:areas}=sandbox;
const base={length:5,width:4,height:3,openingsDeduction:0,includeWalls:true,includeCeiling:false,includeFloor:false,measureLines:[]};
assert.equal(areas(base).walls,54);
const edge={label:'Kanten',unit:'m',hasDimensions:true,length:10.1,width:0,height:1,wallFactor:1,wallFormula:'single',measureOperation:'separate'};
assert.equal(calc(edge),10.1);assert.equal(op(edge),'separate');assert.equal(areas({...base,measureLines:[edge]}).walls,54);
const add={label:'Zusatzfläche',unit:'m²',hasDimensions:false,quantity:4,measureOperation:'add'};
const subtract={label:'Fenster',unit:'m²',quantity:2,measureOperation:'subtract'};
const separate={label:'Eigenfläche',unit:'m²',quantity:40,measureOperation:'separate'};
assert.equal(areas({...base,measureLines:[edge,add,subtract,separate]}).walls,56);
assert.equal(op({unit:'m²',quantity:4}), 'add');
assert.equal(op({unit:'m',measureOperation:'add'}),'separate');
assert.equal(calc({unit:'Stk',hasDimensions:true,wallFactor:5}),5);
assert(src.includes('data-measure-operation')&&src.includes('Zur Hauptfl')&&src.includes('Separat (nicht addieren)'));
assert(server.includes('measureOperation:["add","subtract","separate"]'));
console.log('PASS: Kanten 10.1 m separate, +4 m², -2 m², independent areas and units, old m² still added, operation persists');